# One-time: create SMC\.env with the RTMP ingest settings docker-compose.yml needs.
# Secrets are generated here (random, 256-bit) and never printed. Re-running keeps
# an existing file unless -Force is given (rotating the secrets also needs
# "docker compose up -d" so both containers pick them up).
#
#   RTMP_PUBLIC_HOST   the address CAMERAS use to reach this machine. Defaults to
#                      this PC's LAN IPv4 address; set a DNS name or public IP for
#                      cameras outside the LAN (and forward the RTMP port to it).
param([string]$PublicHost = "", [int]$Port = 1935, [switch]$Force)
$ErrorActionPreference = "Stop"
$envFile = Join-Path (Split-Path $PSScriptRoot -Parent) ".env"   # SMC\.env, next to docker-compose.yml
if ((Test-Path $envFile) -and -not $Force) {
    Write-Host "$envFile already exists (use -Force to replace it)."
    exit 0
}
function New-Secret {
    $bytes = New-Object byte[] 32
    [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
    return ([Convert]::ToBase64String($bytes) -replace '[+/=]', '')
}
if (-not $PublicHost) {
    $cfg = Get-NetIPConfiguration | Where-Object { $_.IPv4DefaultGateway -and $_.NetAdapter.Status -eq "Up" } | Select-Object -First 1
    $PublicHost = $cfg.IPv4Address.IPAddress
}
if (-not $PublicHost) { throw "Could not find this PC's LAN address; pass -PublicHost <address cameras can reach>." }
$hook = New-Secret
$readPw = New-Secret
@"
# =============================================================================
#  SMC Docker settings  (SMC/.env, next to docker-compose.yml)
# =============================================================================
#  Read by "docker compose" for the RTMP ingest server and passed on to the
#  backend container. Created by scripts/docker-ingest-env.ps1.
#  The backend's own settings are in backend/.env.
#  Never commit this file: it holds secrets.
# =============================================================================


# -----------------------------------------------------------------------------
# RTMP push: the address cameras publish to
# -----------------------------------------------------------------------------
# Must be an address the CAMERAS can reach (this PC's LAN IP, or a public
# IP/DNS name with the port forwarded to this PC). Shown on the camera setup
# screen as rtmp://<host>:<port>/live.
RTMP_PUBLIC_HOST=$PublicHost
RTMP_PUBLIC_PORT=$Port
# rtmp, or rtmps once the ingest server has a TLS certificate (mediamtx.yml).
RTMP_PUBLIC_SCHEME=rtmp
# How the one-field "full URL" is built; {server} and {key} are filled in.
# RTMP_FULL_URL_FORMAT={server}/{key}


# -----------------------------------------------------------------------------
# Secrets  (generated by scripts/docker-ingest-env.ps1 - never share)
# -----------------------------------------------------------------------------
# Shared secret the ingest server sends with every auth check to the backend.
INGEST_HOOK_SECRET=$hook
# Password of the backend's read-only account on the ingest server.
INGEST_READ_PASSWORD=$readPw
"@ | Set-Content -Path $envFile -Encoding ascii
Write-Host "Wrote $envFile (RTMP_PUBLIC_HOST=$PublicHost, port $Port; secrets generated, not shown)."
